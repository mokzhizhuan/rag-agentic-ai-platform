BEGIN;

CREATE TABLE IF NOT EXISTS public.camera_devices (
    camera_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(200) NOT NULL,
    location varchar(300) NOT NULL,
    ip_address inet NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'offline',
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT camera_devices_status_check
        CHECK (status IN ('online', 'offline'))
);

CREATE INDEX IF NOT EXISTS idx_camera_devices_status
    ON public.camera_devices (status);

CREATE INDEX IF NOT EXISTS idx_camera_devices_location
    ON public.camera_devices (location);

COMMIT;

SELECT
    COUNT(*) AS online_camera_count
FROM public.camera_devices
WHERE public.camera_devices.status = 'online';

SELECT
    COUNT(*) AS offline_camera_count
FROM public.camera_devices
WHERE public.camera_devices.status = 'offline';

SELECT
    public.camera_devices.status,
    COUNT(*) AS camera_count
FROM public.camera_devices
GROUP BY public.camera_devices.status
ORDER BY public.camera_devices.status;

SELECT
    public.camera_devices.camera_id,
    public.camera_devices.name,
    public.camera_devices.location,
    public.camera_devices.ip_address,
    public.camera_devices.status,
    public.camera_devices.created_at,
    public.camera_devices.updated_at
FROM public.camera_devices
WHERE public.camera_devices.status = $1
ORDER BY public.camera_devices.name;
